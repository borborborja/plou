const CACHE = new Map<Lang, Dict>();

/** Diccionario del idioma pedido, completado con el castellano. */
export function t(lang: Lang): Dict {
  const cached = CACHE.get(lang);
  if (cached) return cached;
  const overrides = lang === 'ca' ? CA : lang === 'en' ? EN : {};
  const merged = { ...DICT.es, ...overrides } as Dict;
  CACHE.set(lang, merged);
  return merged;
}

